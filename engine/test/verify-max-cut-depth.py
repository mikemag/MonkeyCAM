#!/usr/bin/env python3

"""End-to-end G-Code regression checks for maximum cut depth planning."""

import argparse
import copy
import json
import re
import subprocess
import tempfile
from dataclasses import dataclass
from decimal import Decimal
from pathlib import Path


EXAMPLES = {
    "snowboard": (
        "board-def.json",
        "board-binding-def.json",
        None,
    ),
    "ski": ("ski-def.json", "ski-binding-def.json", "30"),
    "splitboard": (
        "splitboard-def.json",
        "splitboard-binding-def.json",
        None,
    ),
}

DEEP_PROGRAMS = {
    "edge": "Sample-splitboard-edge-trench.nc",
    "center": "Sample-splitboard-splitboard-center-trench.nc",
    "cutout": "Sample-splitboard-top-cutout.nc",
    "profile": "Sample-splitboard-top-profile.nc",
}

TOKEN = re.compile(r"\b([XYZF])(-?\d+(?:\.\d+)?)")
MOTION = re.compile(r"^G0[0-3]\b")


class VerificationError(RuntimeError):
    pass


@dataclass(frozen=True)
class FeedMove:
    x: str
    y: str
    z: Decimal
    feed: str


def require(condition, message):
    if not condition:
        raise VerificationError(message)


def read_json(path):
    with path.open(encoding="utf-8") as source:
        return json.load(source)


def write_json(path, value):
    with path.open("w", encoding="utf-8") as destination:
        json.dump(value, destination, indent=2)
        destination.write("\n")


def run_example(binary, repo_root, machine_path, kind, output_dir):
    board, binding, binding_distance = EXAMPLES[kind]
    command = [
        str(binary),
        "--board",
        str(repo_root / "example" / board),
        "--binding",
        str(repo_root / "example" / binding),
        "--machine",
        str(machine_path),
        "--outdir",
        str(output_dir),
    ]
    if binding_distance:
        command.extend(["--bindingdist", binding_distance])
    result = subprocess.run(command, text=True, capture_output=True, check=False)
    if result.returncode != 0:
        raise VerificationError(
            "MonkeyCAM failed for {}:\n{}{}".format(
                kind, result.stdout, result.stderr
            )
        )


def generate_case(binary, repo_root, root, name, machine, kinds):
    case_root = root / name
    case_root.mkdir()
    if isinstance(machine, dict):
        machine_path = case_root / "machine.json"
        write_json(machine_path, machine)
    else:
        machine_path = machine
    outputs = {}
    for kind in kinds:
        output_dir = case_root / kind
        output_dir.mkdir()
        run_example(binary, repo_root, machine_path, kind, output_dir)
        outputs[kind] = output_dir
    return outputs


def output_files(outputs):
    return {
        path.name: path
        for output_dir in outputs.values()
        for path in output_dir.glob("*.nc")
    }


def normalized_lines(path, remove_audit=False):
    result = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if "Generated by MonkeyCAM" in line or re.match(r"^\(\s+at ", line):
            continue
        if remove_audit and (
            "Maximum cut depth:" in line or "Cutting passes:" in line
        ):
            continue
        result.append(line)
    return result


def motion_lines(path):
    return [
        line
        for line in path.read_text(encoding="utf-8").splitlines()
        if MOTION.match(line)
    ]


def bounding_box(path):
    lines = path.read_text(encoding="utf-8").splitlines()
    index = next(
        index for index, line in enumerate(lines)
        if "Cutter bounding box in G54:" in line
    )
    return lines[index + 1].strip()


def cutting_lines(path):
    lines = path.read_text(encoding="utf-8").splitlines()
    start = next(index for index, line in enumerate(lines) if line == "M03")
    end = next(
        index for index, line in enumerate(lines[start + 1 :], start + 1)
        if line == "M05"
    )
    return lines[start + 1 : end]


def cutting_feed_moves(path):
    feed = None
    moves = []
    for line in cutting_lines(path):
        if not line.startswith("G01"):
            continue
        values = dict(TOKEN.findall(line))
        if "F" in values:
            feed = values["F"]
        require(feed is not None, "{}: feed rate is not initialized".format(path.name))
        moves.append(
            FeedMove(values["X"], values["Y"], Decimal(values["Z"]), feed)
        )
    return moves


def cutting_rapid_moves(path):
    moves = []
    for line in cutting_lines(path):
        if not line.startswith("G00"):
            continue
        values = dict(TOKEN.findall(line))
        moves.append((values["X"], values["Y"], values["Z"]))
    return moves


def cutting_feed_groups(path):
    feed = None
    groups = []
    group = []
    for line in cutting_lines(path):
        if line.startswith("G00"):
            if group:
                groups.append(group)
                group = []
            continue
        if not line.startswith("G01"):
            continue
        values = dict(TOKEN.findall(line))
        if "F" in values:
            feed = values["F"]
        require(feed is not None, "{}: feed rate is not initialized".format(path.name))
        group.append(
            FeedMove(values["X"], values["Y"], Decimal(values["Z"]), feed)
        )
    if group:
        groups.append(group)
    return groups


def assert_level_geometry(
    final_moves, emitted_moves, pass_count, label, max_step=None,
    start_depth=Decimal("0.4200")
):
    require(final_moves, "{}: reference path is empty".format(label))
    require(
        len(emitted_moves) == len(final_moves) * pass_count,
        "{}: expected {} passes, got a non-integral motion count".format(
            label, pass_count
        ),
    )
    previous = None
    for level in range(pass_count):
        begin = level * len(final_moves)
        current = emitted_moves[begin : begin + len(final_moves)]
        ceiling = min(move.z for move in current)
        for index, (actual, final) in enumerate(zip(current, final_moves)):
            require(
                (actual.x, actual.y) == (final.x, final.y),
                "{}: X/Y changed at pass {}, point {}".format(
                    label, level + 1, index
                ),
            )
            require(
                actual.feed == final.feed,
                "{}: effective feed changed at pass {}, point {}".format(
                    label, level + 1, index
                ),
            )
            expected_z = final.z if level == pass_count - 1 else max(final.z, ceiling)
            require(
                actual.z == expected_z,
                "{}: Z was not the canonical path clamped to pass {}".format(
                    label, level + 1
                ),
            )
            if max_step is not None:
                prior_z = (
                    max(final.z, start_depth)
                    if previous is None
                    else previous[index].z
                )
                require(
                    prior_z - actual.z <= max_step,
                    "{}: maximum cut depth exceeded at pass {}, point {}".format(
                        label, level + 1, index
                    ),
                )
        previous = current
    require(
        emitted_moves[-len(final_moves) :] == final_moves,
        "{}: final 3D path differs from the one-pass reference".format(label),
    )


def assert_spiral_geometry(reference, actual, pass_count, label, max_step=None):
    require(
        cutting_rapid_moves(reference) == cutting_rapid_moves(actual),
        "{}: rapid move topology changed".format(label),
    )
    require(
        bounding_box(reference) == bounding_box(actual),
        "{}: final cutter bounding box changed".format(label),
    )
    reference_groups = cutting_feed_groups(reference)
    actual_groups = cutting_feed_groups(actual)
    require(
        len(reference_groups) == len(actual_groups),
        "{}: disconnected path count changed".format(label),
    )
    for index, (final_group, actual_group) in enumerate(
        zip(reference_groups, actual_groups)
    ):
        assert_level_geometry(
            final_group,
            actual_group,
            pass_count,
            "{} path {}".format(label, index + 1),
            max_step,
        )


def assert_profile_geometry(reference, actual, pass_count, label, max_step=None):
    reference_moves = cutting_feed_moves(reference)
    actual_moves = cutting_feed_moves(actual)
    assert_level_geometry(
        reference_moves,
        actual_moves,
        pass_count,
        label,
        max_step,
    )
    require(
        bounding_box(reference) == bounding_box(actual),
        "{}: final cutter bounding box changed".format(label),
    )
    reference_rapids = cutting_rapid_moves(reference)
    actual_rapids = cutting_rapid_moves(actual)
    cursor = 0
    for level in range(pass_count):
        if level > 0:
            require(cursor < len(actual_rapids), "{}: missing level retract".format(label))
            prior_endpoint = actual_moves[level * len(reference_moves) - 1]
            retract = actual_rapids[cursor]
            require(
                retract[:2] == (prior_endpoint.x, prior_endpoint.y),
                "{}: level {} does not retract at its endpoint".format(
                    label, level
                ),
            )
            cursor += 1
        require(
            actual_rapids[cursor : cursor + len(reference_rapids)]
            == reference_rapids,
            "{}: canonical rapid X/Y topology changed at pass {}".format(
                label, level + 1
            ),
        )
        cursor += len(reference_rapids)
    require(
        cursor == len(actual_rapids),
        "{}: unexpected rapid moves between depth layers".format(label),
    )


def clear_limits_and_passes(config):
    machine = config["machine"]
    for key in ("edge trench passes", "core cutout passes", "top profile passes"):
        machine.pop(key, None)
    for tool in machine["tools"]:
        tool.pop("max cut depth", None)


def set_tool_maximum(config, tool_id, value):
    for tool in config["machine"]["tools"]:
        if tool["id"] == tool_id:
            tool["max cut depth"] = value
            return
    raise VerificationError("tool {} is missing".format(tool_id))


def assert_audit(path, passes, minimum):
    text = path.read_text(encoding="utf-8")
    require("Maximum cut depth:" in text, "{}: missing maximum audit".format(path.name))
    expected = "Cutting passes: {}, configured minimum: {}".format(passes, minimum)
    require(expected in text, "{}: missing '{}'".format(path.name, expected))


def verify_precedence_case(reference_dir, actual_dir, expected, minimums, max_step):
    for operation in ("edge", "center", "cutout"):
        filename = DEEP_PROGRAMS[operation]
        assert_spiral_geometry(
            reference_dir / filename,
            actual_dir / filename,
            expected[operation],
            operation,
            max_step,
        )
        if max_step is not None:
            assert_audit(actual_dir / filename, expected[operation], minimums[operation])
    filename = DEEP_PROGRAMS["profile"]
    assert_profile_geometry(
        reference_dir / filename,
        actual_dir / filename,
        expected["profile"],
        "profile",
        max_step,
    )
    if max_step is not None:
        assert_audit(actual_dir / filename, expected["profile"], minimums["profile"])


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--monkeycam", required=True, type=Path)
    parser.add_argument(
        "--repo-root", type=Path, default=Path(__file__).resolve().parents[2]
    )
    args = parser.parse_args()
    binary = args.monkeycam.resolve()
    repo_root = args.repo_root.resolve()
    require(binary.is_file(), "MonkeyCAM binary not found: {}".format(binary))

    sample_machine_path = repo_root / "example" / "machine-tool-def.json"
    sample_machine = read_json(sample_machine_path)
    all_kinds = tuple(EXAMPLES.keys())

    with tempfile.TemporaryDirectory(prefix="monkeycam-max-cut-depth-") as temp:
        root = Path(temp)

        canonical = generate_case(
            binary, repo_root, root, "canonical", sample_machine_path, all_kinds
        )
        canonical_files = output_files(canonical)
        checked_in_files = {
            path.name: path for path in (repo_root / "Sample-output").glob("*.nc")
        }
        require(
            set(canonical_files) == set(checked_in_files),
            "canonical generated G-Code file set differs from Sample-output",
        )
        for name, expected_path in checked_in_files.items():
            require(
                normalized_lines(expected_path) == normalized_lines(canonical_files[name]),
                "{}: canonical text differs beyond volatile metadata".format(name),
            )
            require(
                motion_lines(expected_path) == motion_lines(canonical_files[name]),
                "{}: canonical motion differs".format(name),
            )
        print("canonical samples: {} G-Code files unchanged".format(len(canonical_files)))

        nonbinding_machine = copy.deepcopy(sample_machine)
        for tool in nonbinding_machine["machine"]["tools"]:
            tool["max cut depth"] = "1in"
        nonbinding = generate_case(
            binary, repo_root, root, "nonbinding", nonbinding_machine, all_kinds
        )
        nonbinding_files = output_files(nonbinding)
        require(
            set(nonbinding_files) == set(canonical_files),
            "non-binding generated G-Code file set differs",
        )
        for name, expected_path in canonical_files.items():
            require(
                normalized_lines(expected_path, True)
                == normalized_lines(nonbinding_files[name], True),
                "{}: non-binding text differs beyond audit comments".format(name),
            )
            require(
                motion_lines(expected_path) == motion_lines(nonbinding_files[name]),
                "{}: non-binding maximum changed motion".format(name),
            )
        print("non-binding maximums: all G-Code motion unchanged")

        neither_machine = copy.deepcopy(sample_machine)
        clear_limits_and_passes(neither_machine)
        neither = generate_case(
            binary, repo_root, root, "neither", neither_machine, ("splitboard",)
        )["splitboard"]
        one_pass = {operation: 1 for operation in DEEP_PROGRAMS}
        verify_precedence_case(
            neither, neither, one_pass, one_pass, None
        )

        passes_machine = copy.deepcopy(neither_machine)
        passes_machine["machine"].update(
            {
                "edge trench passes": 3,
                "core cutout passes": 2,
                "top profile passes": 3,
            }
        )
        passes = generate_case(
            binary, repo_root, root, "passes", passes_machine, ("splitboard",)
        )["splitboard"]
        passes_expected = {"edge": 3, "center": 3, "cutout": 2, "profile": 3}
        verify_precedence_case(
            neither, passes, passes_expected, passes_expected, None
        )

        maximum_machine = copy.deepcopy(neither_machine)
        set_tool_maximum(maximum_machine, 1, "2mm")
        set_tool_maximum(maximum_machine, 4, "2mm")
        maximum = generate_case(
            binary, repo_root, root, "maximum", maximum_machine, ("splitboard",)
        )["splitboard"]
        maximum_expected = {"edge": 6, "center": 6, "cutout": 6, "profile": 5}
        verify_precedence_case(
            neither,
            maximum,
            maximum_expected,
            one_pass,
            Decimal("0.0788"),
        )

        both_machine = copy.deepcopy(maximum_machine)
        both_machine["machine"].update(
            {
                "edge trench passes": 7,
                "core cutout passes": 7,
                "top profile passes": 6,
            }
        )
        both = generate_case(
            binary, repo_root, root, "both", both_machine, ("splitboard",)
        )["splitboard"]
        both_expected = {"edge": 7, "center": 7, "cutout": 7, "profile": 6}
        verify_precedence_case(
            neither,
            both,
            both_expected,
            {"edge": 7, "center": 7, "cutout": 7, "profile": 6},
            Decimal("0.0788"),
        )
        print("precedence: neither, passes, maximum, and both verified")

        edge_parity_machine = copy.deepcopy(sample_machine)
        set_tool_maximum(edge_parity_machine, 1, "0.140in")
        edge_parity = generate_case(
            binary,
            repo_root,
            root,
            "edge-parity",
            edge_parity_machine,
            ("splitboard",),
        )["splitboard"]
        for operation in ("edge", "center"):
            filename = DEEP_PROGRAMS[operation]
            require(
                motion_lines(canonical["splitboard"] / filename)
                == motion_lines(edge_parity / filename),
                "{}: equivalent maximum changed legacy motion".format(operation),
            )

        cutout_parity_machine = copy.deepcopy(sample_machine)
        set_tool_maximum(cutout_parity_machine, 1, "0.215in")
        cutout_parity = generate_case(
            binary,
            repo_root,
            root,
            "cutout-parity",
            cutout_parity_machine,
            ("splitboard",),
        )["splitboard"]
        cutout_name = DEEP_PROGRAMS["cutout"]
        require(
            motion_lines(canonical["splitboard"] / cutout_name)
            == motion_lines(cutout_parity / cutout_name),
            "cutout: equivalent maximum changed legacy motion",
        )
        print("legacy spiral parity: Edge/Center Trench and Top Cutout exact")

        fixture_path = (
            repo_root / "engine" / "test" / "data" / "machine-max-cut-depth.json"
        )
        fixture = generate_case(
            binary, repo_root, root, "fixture", fixture_path, ("splitboard",)
        )["splitboard"]
        fixture_expected = {"edge": 4, "center": 4, "cutout": 4, "profile": 5}
        for operation in ("edge", "center", "cutout"):
            filename = DEEP_PROGRAMS[operation]
            assert_spiral_geometry(
                neither / filename,
                fixture / filename,
                fixture_expected[operation],
                "fixture {}".format(operation),
                Decimal("0.1182"),
            )
            assert_audit(
                fixture / filename,
                fixture_expected[operation],
                {"edge": 3, "center": 3, "cutout": 2}[operation],
            )
        profile_name = DEEP_PROGRAMS["profile"]
        assert_profile_geometry(
            neither / profile_name,
            fixture / profile_name,
            fixture_expected["profile"],
            "fixture profile",
            Decimal("0.0788"),
        )
        assert_audit(fixture / profile_name, fixture_expected["profile"], 1)
        print("different tool limits: small cutter 3 mm, profile cutter 2 mm")

    print("maximum cut depth regression checks passed")


if __name__ == "__main__":
    try:
        main()
    except (VerificationError, StopIteration, KeyError) as error:
        raise SystemExit("FAIL: {}".format(error))
